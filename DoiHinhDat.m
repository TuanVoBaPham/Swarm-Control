%% plot_formation.m
clc;
clear;
close all;

%% Coordinates
leader   = [0, 0];
follower1 = [-3, -3];
follower2 = [-3, 3];

%% Create figure
figure('Color','w');
hold on;
grid on;
box on;

%% Plot agents
plot(leader(1), leader(2), 'o', ...
    'MarkerSize',8,...
    'LineWidth',1.5,...
    'MarkerEdgeColor',[0 0.4470 0.7410],...
    'MarkerFaceColor','none',...
    'DisplayName','Leader');

plot(follower1(1), follower1(2), 'o', ...
    'MarkerSize',8,...
    'LineWidth',1.5,...
    'MarkerEdgeColor',[0.9290 0.6940 0.1250],...
    'MarkerFaceColor','none',...
    'DisplayName','Follower 1');

plot(follower2(1), follower2(2), '^', ...
    'MarkerSize',8,...
    'LineWidth',1.5,...
    'MarkerEdgeColor',[0.9290 0.6940 0.1250],...
    'MarkerFaceColor','none',...
    'DisplayName','Follower 2');

%% Plot formation lines
plot([leader(1) follower1(1)], [leader(2) follower1(2)], ...
    'k--', 'LineWidth',1,...
    'DisplayName','Formation');

plot([leader(1) follower2(1)], [leader(2) follower2(2)], ...
    'k--', 'LineWidth',1,...
    'HandleVisibility','off');

plot([follower1(1) follower2(1)], [follower1(2) follower2(2)], ...
    'k--', 'LineWidth',1,...
    'HandleVisibility','off');

%% Axes settings
xlabel('X','FontSize',12);
ylabel('Y','FontSize',12);

xlim([-4 4]);
ylim([-4 4]);

xticks(-4:1:4);
yticks(-4:1:4);

axis equal;

%% Legend
legend('Location','northeast');

set(gca,...
    'FontSize',10,...
    'LineWidth',1,...
    'GridAlpha',0.3);
